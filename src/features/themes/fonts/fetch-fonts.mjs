// Wave 2.10b F10 (A11.5 fonts): a one-off developer script that downloads the latin woff2 files of the
// curated built-in families into public/fonts/ and writes their @font-face rules to
// src/styles/theme-fonts.css. It runs by hand, never at build time or at runtime: the browser only ever
// fetches /fonts/*.woff2 from this instance (no font host). Every family is under the SIL Open Font
// License 1.1 (public/fonts/OFL.txt).
//   node src/features/themes/fonts/fetch-fonts.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// family, file slug, Google Fonts css2 weight spec (a variable range, or a static list).
const SELF_HOSTED_FONTS = [
  // sans
  { family: "Manrope", slug: "manrope", weights: "200..800" },
  { family: "DM Sans", slug: "dm-sans", weights: "100..1000" },
  { family: "Work Sans", slug: "work-sans", weights: "100..900" },
  { family: "Public Sans", slug: "public-sans", weights: "100..900" },
  { family: "Figtree", slug: "figtree", weights: "300..900" },
  { family: "Plus Jakarta Sans", slug: "plus-jakarta-sans", weights: "200..800" },
  // serif
  { family: "Lora", slug: "lora", weights: "400..700" },
  { family: "Source Serif 4", slug: "source-serif-4", weights: "200..900" },
  { family: "Merriweather", slug: "merriweather", weights: "300..900" },
  { family: "Playfair Display", slug: "playfair-display", weights: "400..900" },
  { family: "EB Garamond", slug: "eb-garamond", weights: "400..800" },
  { family: "Libre Baskerville", slug: "libre-baskerville", weights: "400..700" },
  { family: "IBM Plex Serif", slug: "ibm-plex-serif", weights: "400;500;600;700" },
  // mono
  { family: "Fira Code", slug: "fira-code", weights: "300..700" },
  { family: "Source Code Pro", slug: "source-code-pro", weights: "200..900" },
  { family: "Space Mono", slug: "space-mono", weights: "400;700" },
  { family: "Roboto Mono", slug: "roboto-mono", weights: "100..700" },
  // display
  { family: "Syne", slug: "syne", weights: "400..800" },
  { family: "Bricolage Grotesque", slug: "bricolage-grotesque", weights: "200..800" },
  { family: "Unbounded", slug: "unbounded", weights: "200..900" },
  { family: "Bebas Neue", slug: "bebas-neue", weights: "400" },
  { family: "Archivo Black", slug: "archivo-black", weights: "400" },
  // rounded
  { family: "Nunito", slug: "nunito", weights: "200..1000" },
  { family: "Quicksand", slug: "quicksand", weights: "300..700" },
  { family: "Varela Round", slug: "varela-round", weights: "400" },
  { family: "Comfortaa", slug: "comfortaa", weights: "300..700" },
  { family: "Fredoka", slug: "fredoka", weights: "300..700" },
];

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../..");
const OUT = path.join(APP, "public/fonts");
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36";
mkdirSync(OUT, { recursive: true });

const rules = [];
for (const f of SELF_HOSTED_FONTS) {
  const q = `family=${f.family.replace(/ /g, "+")}:wght@${f.weights}&display=swap`;
  const css = await (await fetch(`https://fonts.googleapis.com/css2?${q}`, { headers: { "user-agent": UA } })).text();
  // Keep only the latin block(s): one per weight for static families, one for a variable range.
  const blocks = [...css.matchAll(/\/\* latin \*\/\s*@font-face\s*\{([^}]*)\}/g)].map((m) => m[1]);
  if (!blocks.length) throw new Error(`${f.family}: no latin block in ${css.slice(0, 200)}`);
  for (const b of blocks) {
    const url = /src:\s*url\(([^)]+)\)/.exec(b)[1];
    const weight = /font-weight:\s*([0-9 ]+);/.exec(b)[1].trim();
    const range = /unicode-range:\s*([^;]+);/.exec(b)[1].trim();
    const file = `${f.slug}-${weight.replace(" ", "-")}.woff2`;
    const buf = Buffer.from(await (await fetch(url, { headers: { "user-agent": UA } })).arrayBuffer());
    writeFileSync(path.join(OUT, file), buf);
    rules.push(`@font-face {\n  font-family: "${f.family}";\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url("/fonts/${file}") format("woff2");\n  unicode-range: ${range};\n}`);
    console.log(`${f.family} ${weight}: ${file} ${buf.length} bytes`);
  }
}
const header = `/* GENERATED by src/features/themes/fonts/fetch-fonts.mjs (Wave 2.10b F10). Do not edit by hand.
 * The self-hosted built-in theme families beyond the ten next/font ones in src/app/layout.tsx. Latin
 * only, font-display swap. A browser downloads a file only when text on the page uses that family
 * (a theme in use, or an open font picker row), so declaring them all here costs nothing up front. */\n`;
writeFileSync(path.join(APP, "src/features/themes/fonts/theme-fonts.css"), `${header}${rules.join("\n")}\n`);
