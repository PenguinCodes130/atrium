#!/usr/bin/env node
// Writes CODEMAP.md: every URL route and the file that serves it, every source folder with each file's
// one-line purpose (the first sentence of its header comment), and where each area's tests live.
// Generated, never hand-edited: run `pnpm codemap` after moving or adding files. Agents grep it to find
// code instead of reading folders.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, dirname, basename } from "node:path";

const ROOT = join(dirname(new URL(import.meta.url).pathname), "..");
const SRC = join(ROOT, "src");
const SKIP_DIRS = new Set(["node_modules", "__fixtures__", ".next"]);
const isTest = (p) => /__tests__|\/test\/|\.test\.tsx?$|\.spec\.tsx?$/.test(p);
const isSource = (p) => /\.(ts|tsx|mts)$/.test(p) && !p.endsWith(".d.ts");

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP_DIRS.has(name) || name.endsWith(".orig")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// First sentence of the file's leading comment, skipping directives like "use client".
function purpose(text) {
  const lines = text.split("\n");
  let i = 0;
  while (i < lines.length && /^\s*(["']use (client|server)["'];?)?\s*$/.test(lines[i])) i++;
  const body = [];
  if (/^\s*\/\*/.test(lines[i] ?? "")) {
    for (; i < lines.length; i++) {
      body.push(lines[i].replace(/^\s*\/\*\*?|\*\/.*$|^\s*\*\s?/g, ""));
      if (lines[i].includes("*/")) break;
    }
  } else {
    for (; i < lines.length && /^\s*\/\//.test(lines[i]); i++) body.push(lines[i].replace(/^\s*\/\/\s?/, ""));
  }
  const joined = body.join(" ").replace(/\s+/g, " ").trim();
  if (!joined) return "";
  const first = joined.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? joined;
  return first.length > 160 ? first.slice(0, 157) + "..." : first;
}

const HTTP = /export\s+(?:async\s+)?(?:function|const)\s+(GET|POST|PUT|PATCH|DELETE)\b/g;

function routeUrl(file) {
  const rel = relative(join(SRC, "app"), dirname(file));
  const url = "/" + rel.split("/").filter((s) => s && !/^\(.*\)$/.test(s)).map(decodeURIComponent).join("/");
  return url === "/." ? "/" : url;
}

const files = walk(SRC).filter(isSource);
const out = [];
out.push("# Atrium code map");
out.push("");
out.push("GENERATED by `pnpm codemap` (scripts/codemap.mjs). Do not edit by hand; rerun it after moving or adding files.");
out.push("Grep this file (`rg -i <word> CODEMAP.md`) instead of reading it whole. Then use the TypeScript LSP");
out.push("(go to definition, find references) or `rg` inside the folder it points to.");
out.push("");

// Folder overview: feature folders, then everything else.
const byDir = new Map();
for (const f of files) {
  if (isTest(f) || f.startsWith(join(SRC, "app"))) continue;
  const d = relative(ROOT, dirname(f));
  if (!byDir.has(d)) byDir.set(d, []);
  byDir.get(d).push(f);
}
const top = new Map();
for (const [d, fs] of byDir) {
  const key = d.split("/").slice(0, 3).join("/");
  top.set(key, (top.get(key) ?? 0) + fs.length);
}
out.push("## Folders");
out.push("");
out.push("| Folder | Source files | What it is (from its index.ts header, if any) |");
out.push("|---|---|---|");
for (const [k, n] of [...top].sort()) {
  let what = "";
  for (const idx of ["index.ts", "index.tsx"]) {
    try { what = purpose(readFileSync(join(ROOT, k, idx), "utf8")); break; } catch {}
  }
  out.push(`| \`${k}/\` | ${n} | ${what.replace(/\|/g, "\\|")} |`);
}
out.push("");

// Routes.
out.push("## Routes (URL to file)");
out.push("");
out.push("| URL | Kind | File |");
out.push("|---|---|---|");
const routes = files
  .filter((f) => f.startsWith(join(SRC, "app")) && /\/(page|route|layout)\.tsx?$/.test(f))
  .map((f) => {
    const kind = basename(f).replace(/\.tsx?$/, "");
    let k = kind;
    if (kind === "route") k = [...readFileSync(f, "utf8").matchAll(HTTP)].map((m) => m[1]).join(", ") || "route";
    return [routeUrl(f), k, relative(ROOT, f)];
  })
  .sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
for (const [u, k, f] of routes) out.push(`| \`${u}\` | ${k} | \`${f}\` |`);
out.push("");

// Every file with its purpose.
out.push("## Files by folder");
out.push("");
for (const [d, fs] of [...byDir].sort()) {
  out.push(`### ${d}/`);
  for (const f of fs) {
    const text = readFileSync(f, "utf8");
    const client = /^\s*["']use client["']/.test(text) ? " (client)" : "";
    const lines = text.split("\n").length;
    const p = purpose(text);
    out.push(`- \`${basename(f)}\`${client}, ${lines} lines${p ? ": " + p : ""}`);
  }
  out.push("");
}

// Tests: unit tests next to features, e2e by folder.
out.push("## Tests");
out.push("");
out.push("Run only what a change touches: `pnpm exec vitest run <path>` for unit tests; e2e folders need their slot server (see each folder's serve.sh).");
out.push("");
out.push("| Area | Unit test files |");
out.push("|---|---|");
const unit = new Map();
for (const f of files.filter(isTest)) {
  const key = relative(ROOT, f).split("/").slice(0, 3).join("/");
  unit.set(key, (unit.get(key) ?? 0) + 1);
}
for (const [k, n] of [...unit].sort()) out.push(`| \`${k}/\` | ${n} |`);
out.push("");
const e2eRoot = join(ROOT, "tests", "e2e");
try {
  out.push("| E2E folder | Specs | Has serve.sh |");
  out.push("|---|---|---|");
  for (const name of readdirSync(e2eRoot).sort()) {
    const p = join(e2eRoot, name);
    if (!statSync(p).isDirectory()) continue;
    const specs = walk(p).filter((f) => f.endsWith(".spec.ts")).length;
    const serve = readdirSync(p).includes("serve.sh") ? "yes" : "";
    out.push(`| \`tests/e2e/${name}/\` | ${specs} | ${serve} |`);
  }
  out.push("");
} catch {}

writeFileSync(join(ROOT, "CODEMAP.md"), out.join("\n"));
console.log(`CODEMAP.md: ${byDir.size} folders, ${routes.length} routes, ${files.length} source files`);
